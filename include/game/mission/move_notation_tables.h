enum class MoveRole : std::uint8_t {
    DirectInput = 1 << 0,
    InputFollowup = 1 << 1,
    AutomaticPhase = 1 << 2,
    InternalPhase = 1 << 3,
};

constexpr MoveRole operator|(MoveRole lhs, MoveRole rhs) {
    return static_cast<MoveRole>(static_cast<std::uint8_t>(lhs) |
                                 static_cast<std::uint8_t>(rhs));
}

constexpr bool HasRole(MoveRole value, MoveRole role) {
    return (static_cast<std::uint8_t>(value) &
            static_cast<std::uint8_t>(role)) != 0;
}

struct MoveNote {
    short id;
    const char* note;
    MoveRole role;
    const char* route;
    std::uint8_t stage;

    constexpr MoveNote(short moveId, const char* notation, bool automatic)
        : id(moveId), note(notation),
          role(automatic ? MoveRole::AutomaticPhase : MoveRole::DirectInput),
          route(nullptr), stage(0) {}

    constexpr MoveNote(short moveId, const char* notation, MoveRole moveRole,
                       const char* routeFamily = nullptr,
                       std::uint8_t routeStage = 0)
        : id(moveId), note(notation), role(moveRole), route(routeFamily),
          stage(routeStage) {}
};
struct CharTable { const char* name; const MoveNote* entries; int count; };

